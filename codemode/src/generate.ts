import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { schemaToTs, type JsonSchema } from './schema-to-ts.ts';
import type { Tool } from './upstream.ts';

export const camel = (s: string) => s.replace(/[-_. ]+([a-zA-Z0-9])/g, (_, c: string) => c.toUpperCase()).replace(/^[^a-zA-Z_$]/, '_$&');
const pascal = (s: string) => camel(s).replace(/^./, (c) => c.toUpperCase());
export const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'server';

const hasRequired = (t: Tool) => ((t.inputSchema as JsonSchema).required ?? []).length > 0;
const doc = (text: string | undefined, indent = '') =>
  text ? `${indent}/**\n${text.replace(/\*\//g, '* /').split('\n').map((l) => `${indent} * ${l}`.trimEnd()).join('\n')}\n${indent} */\n` : '';

/** One wrapper per tool. It only forwards to the MCP server through `callTool`. */
export function renderTool(t: Tool, server: string): string {
  const fn = camel(t.name);
  const type = `${pascal(t.name)}Input`;
  return `// Generated by figma-design-validator-codemode from ${server}. Do not edit: run \`generate\`.
import { callTool } from './_call.ts';

export type ${type} = ${schemaToTs(t.inputSchema as JsonSchema)};

${doc(t.description)}export function ${fn}(input: ${type}${hasRequired(t) ? '' : ' = {}'}): Promise<unknown> {
  return callTool(${JSON.stringify(t.name)}, input);
}
`;
}

/** One line per tool for progressive disclosure: name, input shape without docs, first sentence. */
export function signature(t: Tool): string {
  const input = schemaToTs(t.inputSchema as JsonSchema).replace(/\/\*\*[^]*?\*\//g, '').replace(/\s+/g, ' ').replace(/; }/g, ' }');
  const first = (t.description ?? '').split(/(?<=\.)\s/)[0];
  return `tools.${camel(t.name)}(input${hasRequired(t) ? '' : '?'}: ${input}): Promise<unknown>${first ? ` // ${first}` : ''}`;
}

const CALL = `// Generated by figma-design-validator-codemode. Do not edit: run \`generate\`.
/**
 * Provided by the code mode sandbox. Forwards to the MCP server through the host bridge,
 * which validates arguments and applies the allow list and confirmation gate.
 * Resolves to the tool's JSON result (or text); rejects with the tool's error.
 */
export declare function callTool(name: string, input: object): Promise<unknown>;
`;

/** All generated files, keyed by path relative to the output dir. */
export function renderAll(server: string, tools: Tool[]): Map<string, string> {
  const dir = slug(server);
  const files = new Map<string, string>([[`${dir}/_call.ts`, CALL]]);
  const sorted = [...tools].sort((a, b) => a.name.localeCompare(b.name));
  for (const t of sorted) files.set(`${dir}/${camel(t.name)}.ts`, renderTool(t, server));
  files.set(
    `${dir}/index.ts`,
    `// Generated by figma-design-validator-codemode from ${server}. Do not edit: run \`generate\`.\n` +
      sorted.map((t) => `export * from './${camel(t.name)}.ts';`).join('\n') +
      '\n',
  );
  return files;
}

/** Write the wrappers, or with `check` report which files differ. Stale files in the server's dir are removed/reported. */
export async function syncFiles(outDir: string, server: string, files: Map<string, string>, check: boolean): Promise<string[]> {
  const stale: string[] = [];
  const dir = join(outDir, slug(server));
  const existing = await readdir(dir).catch(() => [] as string[]);
  for (const f of existing) {
    const rel = `${slug(server)}/${f}`;
    if (!files.has(rel)) {
      stale.push(rel);
      if (!check) await rm(join(outDir, rel));
    }
  }
  for (const [rel, content] of files) {
    const p = join(outDir, rel);
    const cur = await readFile(p, 'utf8').catch(() => undefined);
    if (cur === content) continue;
    stale.push(rel);
    if (!check) {
      await mkdir(dirname(p), { recursive: true });
      await writeFile(p, content);
    }
  }
  return stale;
}
